"""The project boundary, waves, and levels.

Revision ID: 0001
Revises:

The schema is carried over from the Java's Flyway migrations, which worked through these
decisions once already. Three things change, and all three are the same change: PostgreSQL is
the only dialect here, so rules the Java had to move into a vendor directory — where its H2
slice tests could not see them — live in the one schema and are proved by the tests that run
on every build.
"""

from alembic import op

revision = "0001"
down_revision = None
branch_labels = None
depends_on = None


def upgrade() -> None:
    # One row for the life of a self-hosted deployment. It exists now because the alternative
    # is adding a tenant column to a finished schema later, which means touching every table,
    # foreign key, index, query and URL at once.
    #
    # Ids are generated by the application, not by a database default: an entity then has its
    # identity before it is written, which is what lets a caller build a graph of related rows
    # in one transaction.
    op.execute("""
        create table project (
            id          uuid         not null,
            slug        varchar(64)  not null,
            name        varchar(120) not null,
            created_at  timestamptz  not null,
            constraint pk_project primary key (id),
            constraint uq_project_slug unique (slug),
            constraint ck_project_slug_format check (slug ~ '^[a-z0-9_]+$')
        )
    """)

    # The column pair the whole content design hangs off.
    #
    #   config_json text   the bytes the client sent, stored verbatim
    #   config      jsonb  generated from them, for indexing only
    #
    # The ETag for a raw document is a hash of the stored bytes, so those bytes have to be
    # stable. jsonb is not: PostgreSQL reorders keys and normalises numbers, so a document
    # written as {"b":1,"a":2.0} reads back as {"a":2.0,"b":1}. Re-serialising on the write
    # path is no better. Neither breaks anything visibly — both move the ETag on every save
    # even when the author changed nothing, and every installed client then re-downloads the
    # whole catalogue on its next launch. On mobile that is a bandwidth bill arriving weeks
    # later with nothing obvious to connect it to.
    op.execute("""
        create table wave (
            project_id      uuid         not null,
            wave_id         varchar(64)  not null,
            content_type    varchar(64)  not null default 'wave',
            schema_uri      varchar(512) not null,
            schema_version  integer      not null,
            name            varchar(255) not null,
            wave_order      integer      not null,
            published       boolean      not null default false,
            config_json     text         not null,
            config          jsonb generated always as (config_json::jsonb) stored,
            created_at      timestamptz  not null,
            updated_at      timestamptz  not null,

            constraint pk_wave primary key (project_id, wave_id),
            constraint fk_wave_project foreign key (project_id)
                references project (id) on delete cascade,
            constraint ck_wave_id_format check (wave_id ~ '^[a-z0-9_]+$'),
            constraint ck_wave_order_not_negative check (wave_order >= 0),
            constraint ck_wave_schema_version_positive check (schema_version >= 1)
        )
    """)
    # An order collision is a constraint violation rather than racy application logic: two
    # concurrent writes cannot both succeed in claiming order 3.
    op.execute("create unique index uq_wave_order on wave (project_id, wave_order)")
    # The only list query the serving routes make.
    op.execute("create index ix_wave_published on wave (project_id, published)")
    op.execute("create index ix_wave_config on wave using gin (config)")

    op.execute("""
        create table wave_level (
            id          uuid         not null,
            project_id  uuid         not null,
            name        varchar(255) not null,
            description text,
            active      boolean      not null default false,
            created_at  timestamptz  not null,
            updated_at  timestamptz  not null,

            constraint pk_wave_level primary key (id),
            constraint fk_wave_level_project foreign key (project_id)
                references project (id) on delete cascade,
            -- Redundant against the primary key and required: it is the key the membership
            -- table's composite foreign key points at, which is what makes a level and its
            -- waves provably belong to the same project rather than usually belonging to it.
            constraint uq_wave_level_id_project unique (id, project_id)
        )
    """)
    op.execute("create index ix_wave_level_project on wave_level (project_id, name)")

    # "Exactly one active level per project", as a rule the database keeps.
    #
    # The Java wanted this and could not have it: a partial index is PostgreSQL-only, its slice
    # tests ran on H2, and a rule absent there is a rule those tests cannot prove — so it used a
    # separate table instead. With one dialect the obvious design is also the provable one.
    op.execute(
        "create unique index uq_wave_level_one_active on wave_level (project_id) where active"
    )

    op.execute("""
        create table wave_level_wave (
            project_id     uuid        not null,
            wave_level_id  uuid        not null,
            wave_id        varchar(64) not null,
            position       integer     not null,

            constraint pk_wave_level_wave primary key (wave_level_id, wave_id),
            -- Keyed on (id, project_id) rather than id alone, so this row's project_id cannot
            -- disagree with the level's: a row claiming a level from project A and a wave from
            -- project B does not fail a check somewhere, it fails to be insertable.
            constraint fk_wave_level_wave_level foreign key (wave_level_id, project_id)
                references wave_level (id, project_id) on delete cascade,
            -- A wave is identified by (project_id, wave_id), so a reference carries both.
            -- Deleting a wave removes it from every level, in the database, rather than in
            -- whichever service method happened to remember.
            constraint fk_wave_level_wave_wave foreign key (project_id, wave_id)
                references wave (project_id, wave_id) on delete cascade,
            constraint uq_wave_level_wave_position unique (wave_level_id, position),
            constraint ck_wave_level_wave_position_not_negative check (position >= 0)
        )
    """)


